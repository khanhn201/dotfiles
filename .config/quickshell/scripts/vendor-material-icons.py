def load(name: str) -> str:
    with open(f"{SRC_DIR}/{name}.svg") as f:
        svg = f.read()
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    svg = re.sub(r'\s(width|height)="[^"]*"', "", svg)
    svg = svg.strip()
    # Material Symbols' source sets no fill at all -- SVG then defaults to
    # solid black, not transparent/inherit -- so SvgIcon's recolor always has
    # an attribute to overwrite regardless of which icon this is.
    if 'fill="' not in svg.split(">", 1)[0]:
        svg = svg.replace("<svg ", '<svg fill="#000000" ', 1)
    # One line, and quote-safe for embedding in a QML double-quoted string.
    svg = " ".join(svg.split())
    svg = svg.replace('"', '\\"')
    return svg


entries = []
for key, fname in ICONS.items():
    entries.append(f'        {key}: "{load(fname)}"')
entries_block = ",\n".join(entries)

qml = f'''// Generated by quickshell/scripts/vendor-material-icons.py -- do not edit by
// hand. Material Symbols (rounded, weight 400), Apache-2.0.
// Source: @material-symbols/svg-400 (npm).
pragma Singleton
import Quickshell

Singleton {{
    readonly property var svg: ({{
{entries_block}
    }})
}}
'''

with open(OUT_PATH, "w") as f:
    f.write(qml)

print(f"wrote {OUT_PATH} ({len(ICONS)} icons, {len(qml)} bytes)")
