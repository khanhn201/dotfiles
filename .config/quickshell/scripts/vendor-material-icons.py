"""Vendors a fixed set of Material Symbols (rounded, weight 400) glyphs into
quickshell/Icons.qml as inline SVG strings, so the bar's icons render as real
vector art instead of mixed Nerd Font glyphs (which don't share one drawing
canvas, so unrelated glyphs land at different optical sizes at the same
font-size -- see the muted-volume icon issue this replaces).

Source package: @material-symbols/svg-400 (npm). Re-run after `npm install
@material-symbols/svg-400` in a scratch directory if the icon list below
changes; nothing at runtime depends on npm or node_modules.
"""
